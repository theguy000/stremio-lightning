/// The language's own name for `code`, if the code is one the table knows.
pub(crate) fn label(code: &str) -> Option<&'static str> {
    NAMES
        .iter()
        .find(|(known, _)| known.eq_ignore_ascii_case(code))
        .map(|(_, name)| *name)
}

/// The same, falling back to the code itself -- which is what the web does for a language the
/// package does not list (Brazilian Portuguese, "pob", is one).
pub(crate) fn label_or_code(code: &str) -> String {
    label(code).map_or_else(|| code.to_owned(), str::to_owned)
}

#[cfg(test)]
mod tests {
    use super::{label, label_or_code};

    #[test]
    fn a_language_is_named_in_its_own_language() {
        assert_eq!(label("ger"), Some("Deutsch"));
        assert_eq!(label("deu"), Some("Deutsch"));
        assert_eq!(label("de"), Some("Deutsch"));
    }

    #[test]
    fn an_unknown_code_stands_in_for_itself() {
        // `pob` is the Brazilian Portuguese code the subtitle addons use, and `langs` has no row
        // for it -- the web shows the code then, and so do we.
        assert_eq!(label("pob"), None);
        assert_eq!(label_or_code("pob"), "pob");
    }
}
